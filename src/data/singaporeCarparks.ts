export type CarparkAgency = 'HDB' | 'LTA' | 'URA';

export type SingaporeRegion = 'Central' | 'East' | 'North' | 'North-East' | 'West';

export type CarparkType =
  | 'MULTI-STOREY CAR PARK'
  | 'BASEMENT CAR PARK'
  | 'SURFACE CAR PARK'
  | 'MECHANISED AND SURFACE CAR PARK';

export interface LotBreakdown {
  totalLots: number;
  availableLots: number;
}

export interface CarparkMetadata {
  id: string; // e.g. "ACB", "BM29", "1" (LTA), "U0012" (URA)
  name: string;
  address: string;
  town: string;
  region: SingaporeRegion;
  agency: CarparkAgency;
  carparkType: CarparkType;
  parkingSystem: 'ELECTRONIC PARKING' | 'COUPON PARKING';
  lat: number;
  lng: number;
  rates: {
    weekdayPerHalfHour: number; // SGD
    weekendPerHalfHour: number; // SGD
    centralAreaPeakSurcharge?: boolean;
    nightParkingAvailable: boolean;
    freeParkingInfo: string;
    gracePeriodMins: number;
  };
  gantryHeightMeters: number;
  evChargersCount: number;
  hasSeasonParking: boolean;
  defaultLots: {
    C: LotBreakdown; // Cars
    Y: LotBreakdown; // Motorcycles
    H: LotBreakdown; // Heavy Vehicles
  };
}

export interface LiveCarpark extends CarparkMetadata {
  lots: {
    C: LotBreakdown;
    Y: LotBreakdown;
    H: LotBreakdown;
  };
  distanceKm: number;
  walkingMins: number;
  drivingMins: number;
  occupancyRate: number; // 0 to 100
  statusLabel: 'Plenty' | 'Moderate' | 'Filling Fast' | 'Full';
  lastUpdated: string;
  isLiveApiSynced: boolean;
  hourlyForecast: number[]; // 24 hours predicted availability %
}

